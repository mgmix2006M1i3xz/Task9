#include <stdio.h>
#include <locale.h>
#include <math.h>

int word1() {
    // 1. Полная таблица Пифагора
    printf("=== 1. Полная таблица Пифагора ===\n");
    for (int row = 1; row <= 9; row++) {
        for (int col = 1; col <= 9; col++) {
            printf("%4d", col * row); // %4d для ровных столбцов
        }
        printf("\n");
    }
    printf("\n"); 

    // 2. Левый нижний треугольник таблицы Пифагора
    printf("=== 2. Левый нижний треугольник ===\n");
    for (int row = 1; row <= 9; row++) {
        // Внутренний цикл идет только до текущего номера строки (col <= row)
        for (int col = 1; col <= row; col++) {
            printf("%4d", col * row);
        }
        printf("\n");
    }
    printf("\n"); 

    // 3. Печать таблицы умножения в формате варианта 16
    printf("=== 3. Таблица умножения (вариант 16) ===\n");
    for (int i = 1; i <= 9; i++) { // Первый множитель (строка)
        for (int j = 1; j <= 9; j++) { // Второй множитель (столбец)
            // Форматирование с выравниванием: %d x %d = %-3d (минус слева)
            printf("%d x %d = %-3d", i, j, i * j);

            // Разделяем тройки примеров отступами для красоты, как на фото
            if (j % 3 == 0 && j != 9) {
                printf("\t");
            }
        }
        printf("\n"); // Переход на новую строку после вывода всех j для текущего i
    }

    return 0;
}
int word2() {
    long long number;
    char continue_choice;

    // Используем цикл с постусловием do-while для повторения программы
    do {
        int count_3 = 0;     // Для пункта 1
        int count_even = 0;  // Для пункта 3

        printf("\nВведите целое число: ");
        scanf("%lld", &number);

        // Делаем копию числа, так как при делении оно будет меняться
        long long temp = number;

        // Если ввели отрицательное число, берем по модулю (чтобы работало корректно)
        if (temp < 0) temp = -temp;

        // Обработка особого случая: если ввели 0
        if (temp == 0) {
            count_even = 1;
        }

        // Цикл разложения числа на цифры
        while (temp > 0) {
            int digit = temp % 10; // Получаем последнюю цифру

            // 1) Количество цифр 3
            if (digit == 3) {
                count_3++;
            }

            // 3) Количество четных цифр
            if (digit % 2 == 0) {
                count_even++;
            }

            // (Здесь можно добавить логику для остальных 10 пунктов, используя digit)

            temp = temp / 10; // Отбрасываем последнюю цифру
        }

        printf("Результаты для числа %lld:\n", number);
        printf("1) Количество цифр '3': %d\n", count_3);
        printf("3) Количество четных цифр: %d\n", count_even);

        // Модернизация: запрос на продолжение
        printf("\nПродолжить? (Да - y, Нет - n): ");
        // Пробел перед %c нужен, чтобы пропустить символ перевода строки (\n) от предыдущего ввода
        scanf(" %c", &continue_choice);

    } while (continue_choice != 'n' && continue_choice != 'N');

    printf("Программа завершена.\n");
    return 0;
}

int word3() {
    int height, width;
    char symbol;
    int choice;

    do {
        printf("\nВведите символ из которого будет строиться фигура: ");
        // Пробел перед %c игнорирует предыдущие нажатия Enter
        scanf(" %c", &symbol);

        printf("Введите высоту: ");
        scanf("%d", &height);

        printf("Введите ширину: ");
        scanf("%d", &width);

        printf("Пустой прямоугольник внутри:\n\n");

        // Внешний цикл отвечает за строки (высоту)
        for (int i = 1; i <= height; i++) {

            // Внутренний цикл отвечает за столбцы (ширину)
            for (int j = 1; j <= width; j++) {

                // Условие печати контура:
                // Если это первая строка (i == 1), последняя строка (i == height),
                // первый столбец (j == 1) или последний столбец (j == width)
                if (i == 1 || i == height || j == 1 || j == width) {
                    printf("%c", symbol);
                }
                else {
                    // Внутри прямоугольника печатаем пробел
                    printf(" ");
                }
            }
            // Переход на новую строку после завершения текущей
            printf("\n");
        }

        // Модернизация (повтор программы по желанию пользователя)
        printf("\nПродолжить? (Да - введите любое число, Нет - введите 0): ");
        scanf("%d", &choice);

    } while (choice != 0);

    return 0;
}

